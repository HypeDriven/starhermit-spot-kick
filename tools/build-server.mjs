// Writes server.js, the platform's one server script, from tools/server-head.js,
// the shared rules (js/rules.js, a UMD script, wrapped so its export becomes
// `SpotKickRules`) and tools/server-body.js. The platform runs server.js as one
// classic script (no imports), so the rules are inlined.
//
//   node tools/build-server.mjs          rewrite server.js
//   node tools/build-server.mjs --check  exit 1 when server.js is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (f) => readFileSync(ROOT + f, 'utf8');
const rules = read('js/rules.js').replace(/^'use strict';\s*/, '').trim();
const next = [
  read('tools/server-head.js').trim(),
  '',
  '// RULES:BEGIN — generated by tools/build-server.mjs from js/rules.js; do not edit.',
  'var SpotKickRules = (function () {',
  '  var module = { exports: {} };',
  rules,
  '  return module.exports;',
  '})();',
  '// RULES:END',
  '',
  read('tools/server-body.js').trim(),
  '',
].join('\n');
const file = ROOT + 'server.js';
let cur = '';
try { cur = readFileSync(file, 'utf8'); } catch { /* new */ }
if (process.argv.includes('--check')) {
  if (next !== cur) { console.error('server.js is stale — run npm run server'); process.exit(1); }
  console.log('server.js current');
} else if (next !== cur) { writeFileSync(file, next); console.log('server.js written'); }
else console.log('server.js current');
